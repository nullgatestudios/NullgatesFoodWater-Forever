"""Builds Data/ConjureRanks.lua from the Forever client's tables on wago.tools.

Every spell named "Conjure Food" or "Conjure Water" whose effect creates an item
(SpellEffect.Effect 24) becomes one rank: the spell ID, the item it makes, the
item's required level (ItemSparse.RequiredLevel), how many it makes per cast and
the level the spell is learned at (SpellLevels). The addon only offers ranks the
player knows, so extra entries (a non-trainer variant, say) are harmless.

Usage:
  python tools/generate_conjure_ranks.py [--build 1.60.1.70532] [--data DIR]

  --build  the client build to read (default: the latest wow_classic_beta build, which is Forever)
  --data   read SpellName.csv, SpellEffect.csv, SpellLevels.csv and ItemSparse.csv from DIR
           instead of downloading them
"""
import argparse
import csv
import io
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "NullgatesFoodWater-Forever", "Data", "ConjureRanks.lua")
TABLES = ("SpellName", "SpellEffect", "SpellLevels", "ItemSparse")
KINDS = {"Conjure Food": "food", "Conjure Water": "water"}
CREATE_ITEM = "24"


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "NullgatesFoodWater-generator"})
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read().decode("utf-8")


def latest_build():
    builds = json.loads(fetch("https://wago.tools/api/builds/latest"))
    return builds["wow_classic_beta"]["version"]


def load(name, build, data_dir):
    if data_dir:
        with open(os.path.join(data_dir, name + ".csv"), encoding="utf-8") as f:
            text = f.read()
    else:
        text = fetch("https://wago.tools/db2/%s/csv?build=%s" % (name, build))
    return list(csv.DictReader(io.StringIO(text)))


def to_int(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def build_ranks(tables):
    names = {to_int(r["ID"]): r["Name_lang"] for r in tables["SpellName"]}
    levels = {to_int(r["SpellID"]): r for r in tables["SpellLevels"] if to_int(r["DifficultyID"]) == 0}
    items = {to_int(r["ID"]): r for r in tables["ItemSparse"]}
    ranks = {"food": [], "water": []}
    for effect in tables["SpellEffect"]:
        spell = to_int(effect["SpellID"])
        kind = KINDS.get(names.get(spell, ""))
        if not kind or effect["Effect"] != CREATE_ITEM or to_int(effect["DifficultyID"]) != 0:
            continue
        item = to_int(effect["EffectItemType"])
        if item not in items:
            continue
        lv = levels.get(spell, {})
        learn = to_int(lv.get("BaseLevel")) or to_int(lv.get("SpellLevel"))
        ranks[kind].append({
            "spell": spell,
            "item": item,
            "itemName": items[item]["Display_lang"],
            "itemLevel": max(1, to_int(items[item]["RequiredLevel"])),
            "count": max(1, to_int(effect.get("EffectBasePointsF"))),
            "learnLevel": learn,
        })
    for kind in ranks:
        ranks[kind].sort(key=lambda r: (r["itemLevel"], r["count"], r["learnLevel"], r["spell"]))
    return ranks


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(ranks, build, path):
    lines = [
        "-- Conjure Food and Conjure Water ranks, generated by tools/generate_conjure_ranks.py",
        "-- from the Forever client's tables (build %s). Do not edit by hand; re-run the" % build,
        "-- generator for a new client build.",
        "--   spell = spell ID, item = item it makes, itemLevel = the item's required level,",
        "--   count = items per cast, learnLevel = level the spell is learned at (its base level, or spell level when it has none)",
        "local _, ns = ...",
        "",
        'ns.CONJURE_DATA_BUILD = "%s"' % build,
        "ns.CONJURE_RANKS = {",
    ]
    for kind in ("food", "water"):
        lines.append("    %s = {" % kind)
        for r in ranks[kind]:
            lines.append("        { spell = %d, item = %d, itemLevel = %d, count = %d, learnLevel = %d }, -- %s" % (
                r["spell"], r["item"], r["itemLevel"], r["count"], r["learnLevel"], r["itemName"]))
        lines.append("    },")
    lines.append("}")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build")
    parser.add_argument("--data")
    args = parser.parse_args()
    build = args.build or latest_build()
    tables = {name: load(name, build, args.data) for name in TABLES}
    ranks = build_ranks(tables)
    if not ranks["food"] or not ranks["water"]:
        sys.exit("No Conjure Food or Conjure Water ranks found in build %s" % build)
    write_lua(ranks, build, OUT)
    print("Build %s: %d food ranks, %d water ranks -> %s" % (build, len(ranks["food"]), len(ranks["water"]), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
